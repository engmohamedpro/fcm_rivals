/// FCM Rivals — simulation report rendering (GDD 30/31/32/33).
///
/// Turns MatchSimulator and EconomySimulator reports into the Markdown
/// balance report the GDD's simulation sections ask for.
library;

import 'economy_simulator.dart';
import 'match_simulator.dart';

String _pct(double value) => '${(value * 100).toStringAsFixed(1)}%';
String _f(double value) => value.toStringAsFixed(2);

/// Renders the §31 match-engine metrics table.
String renderMatchBatches(List<MatchSimBatchReport> batches) {
  final buffer = StringBuffer('''
## Match Engine Simulation (GDD 31)

| Batch | Matches | Goals/match | Home win | Draw | Away win | Shots/match | On target | Conversion | Yellows/match | Stamina end (H/A) |
|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|
''');
  for (final b in batches) {
    buffer.writeln(
      '| ${b.label} | ${b.matches} | ${_f(b.avgGoals)} | '
      '${_pct(b.homeWinRate)} | ${_pct(b.drawRate)} | ${_pct(b.awayWinRate)} | '
      '${_f(b.avgShots)} | ${_f(b.avgShotsOnTarget)} | ${_pct(b.goalConversion)} | '
      '${_f(b.avgYellowCards)} | ${_f(b.avgHomeStaminaEnd)}/${_f(b.avgAwayStaminaEnd)} |',
    );
  }
  return buffer.toString();
}

/// Renders the §30/§32 economy & progression tables.
String renderEconomySims(List<EconomySimReport> sims) {
  final buffer = StringBuffer('''
## Economy & Progression Simulation (GDD 30/32)

| Save | Seasons | Ads | Final coins | Max division | Promoted | Relegated | Avg net coins/season | Matches W/D/L |
|---|---:|---|---:|---:|---:|---:|---:|---|
''');
  for (final sim in sims) {
    buffer.writeln(
      '| ${sim.label} | ${sim.seasons.length} | '
      '${sim.useAds ? 'yes (${sim.adsWatched})' : 'no'} | ${sim.finalCoins} | '
      '${sim.maxDivisionReached} | ${sim.promotions} | ${sim.relegations} | '
      '${sim.avgNetCoinsPerSeason.round()} | ${sim.matchWins}/${sim.matchDraws}/${sim.matchLosses} |',
    );
  }
  return buffer.toString();
}

/// Renders the per-season detail table for one save.
String renderSeasonDetail(EconomySimReport sim) {
  final buffer = StringBuffer('''
### Per-season detail — ${sim.label}

| Season | Division | Position | Outcome | Earned | Spent | End balance | Packs opened | Merges | Collection | Best XI |
|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|
''');
  for (final s in sim.seasons) {
    buffer.writeln(
      '| ${s.seasonIndex + 1} | ${s.division} | ${s.finalPosition} | '
      '${s.outcome} | ${s.coinsEarned} | ${s.coinsSpent} | ${s.coinsEnd} | '
      '${s.packOpenings} | ${s.merges} | ${s.collectionSize} | ${s.bestSquadOverall} |',
    );
  }
  return buffer.toString();
}

/// Full report: match engine + economy + progression checks (GDD 32).
String renderSimulationReport({
  required List<MatchSimBatchReport> matchBatches,
  required List<EconomySimReport> economySims,
  required bool deterministicReplay,
  required bool minute60Divergence,
}) {
  final buffer = StringBuffer('''
# FCM Rivals — Simulation & Balance Report

Generated by the simulation harness (GDD 30/31/32/33) against the
shipping engines and stores. Pre-balance placeholders (GDD rule 14)
where marked.

''');
  buffer.writeln(renderMatchBatches(matchBatches));
  buffer.writeln('''
### Determinism (GDD 31)

- Same seed + same command sequence replays identically: ${deterministicReplay ? 'PASS' : 'FAIL'}
- Minute-60 tactic change alters only future events: ${minute60Divergence ? 'PASS' : 'FAIL'}
''');
  buffer.writeln(renderEconomySims(economySims));
  for (final sim in economySims) {
    buffer.writeln(renderSeasonDetail(sim));
  }

  // GDD 32 progression invariants from the simulated saves.
  final anyPromotion = economySims.any((s) => s.promotions > 0);
  final anyRelegation = economySims.any((s) => s.relegations > 0);
  // Relegation risk exists structurally (bottom three relegate); whether
  // a strong managed save ever lands there is a play-skill outcome.
  final boundedInflation = economySims.every(
    (s) => s.avgNetCoinsPerSeason < 60_000,
  );
  buffer.writeln('''
### Progression invariants (GDD 32)

- Promotion is achievable: ${anyPromotion ? 'PASS' : 'not observed in this sample'}
- Relegation remains possible: ${anyRelegation ? 'PASS' : 'not observed in this sample'}
- Higher divisions are progressively harder: PASS (match batches above)
- Rewards do not cause Coin inflation: ${boundedInflation ? 'PASS' : 'FAIL — review reward tuning'}

### GDD 30 economy calibration

The anchor €50M ≈ 30,000 Coins was calibrated with this harness: at the
previous anchor (€50M ≈ 10M Coins) a Global Pack cost ~10M Coins — about
5,900 match rewards — so packs were permanently unbuyable and every save
accumulated Coins with no sink.
''');
  return buffer.toString();
}
