/// Home nations have no ISO country code; they use emoji tag sequences
/// (black flag + subdivision tag letters + cancel tag).
const Map<String, String> _subdivisionTags = {
  'England': 'gbeng',
  'Scotland': 'gbsct',
  'Wales': 'gbwls',
};

String _tagSequence(String tag) {
  final b = StringBuffer(String.fromCharCode(0x1F3F4));
  for (final unit in tag.codeUnits) {
    b.writeCharCode(0xE0000 + unit);
  }
  b.writeCharCode(0xE007F);
  return b.toString();
}

/// Flag emoji for [nationality], or a football when unknown.
String flagEmojiFor(String nationality) {
  final tag = _subdivisionTags[nationality];
  if (tag != null) return _tagSequence(tag);
  final iso = _isoByNationality[nationality];
  if (iso == null || iso.length != 2) return '\u26BD';
  // Regional indicator letters: 'A' (0x41) -> U+1F1E6.
  return String.fromCharCodes([
    for (final c in iso.codeUnits) 0x1F1E6 + (c - 0x41),
  ]);
}
